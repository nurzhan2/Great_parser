#!/bin/bash
# Единственный правильный способ запустить обход. Закрывает все грабли,
# на которых он уже падал:
#   • cd в каталог проекта (иначе «No module named banner_parser»);
#   • python3, а не /usr/bin/python (пакеты стоят только под 3.10);
#   • YOLO_CONFIG_DIR в /tmp (~/.config/Ultralytics недоступен на запись);
#   • python -u + файловый лог (иначе хвост лога теряется при убийстве процесса);
#   • блокировка от параллельного запуска (обход резюмируемый, но не параллельный);
#   • понятный код возврата и итоговая строка о причине остановки.
#
# ВАЖНО про shared-хостинг: процесс живёт только пока жива SSH-сессия.
# nohup, setsid, screen и tmux проверены — не спасают, всю сессию сносят целиком.
# Поэтому либо держите SSH открытым, либо запускайте этот скрипт из планировщика
# в панели Beget с ограничением --limit, чтобы каждый запуск заканчивался сам.
#
# Использование:
#   scripts/run_crawl.sh                       # 200 панорам за запуск
#   scripts/run_crawl.sh --limit 500           # свой лимит
#   BP_LON=37.62 BP_LAT=55.75 scripts/run_crawl.sh
#   Любые аргументы уходят в `banner_parser crawl` как есть.

set -uo pipefail

PROJECT_DIR="${BP_PROJECT_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
LON="${BP_LON:-37.7050}"
LAT="${BP_LAT:-55.6480}"
LIMIT="${BP_LIMIT:-200}"

TS="$(date +%Y%m%d_%H%M%S)"
LOG_DIR="$PROJECT_DIR/logs"
LOG="$LOG_DIR/crawl_$TS.log"
LOCK="$PROJECT_DIR/logs/crawl.lock"

mkdir -p "$LOG_DIR" 2>/dev/null

# Пишем и на экран, и в лог: если упадёт сам wrapper, причина всё равно в файле.
say() { printf '%s WRAPPER %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*" | tee -a "$LOG"; }
die() { say "ФАТАЛЬНО: $*"; exit 2; }

say "=== запуск обхода ==="
say "каталог проекта : $PROJECT_DIR"
cd "$PROJECT_DIR" || die "каталог $PROJECT_DIR недоступен"

# --- python -----------------------------------------------------------------
PY="$(command -v python3 || true)"
[ -n "$PY" ] || die "python3 не найден в PATH ($PATH)"
say "интерпретатор   : $PY ($("$PY" -V 2>&1))"

# --- окружение --------------------------------------------------------------
export YOLO_CONFIG_DIR="${YOLO_CONFIG_DIR:-/tmp/Ultralytics}"
export MPLCONFIGDIR="${MPLCONFIGDIR:-/tmp/mpl}"
export HF_HUB_DISABLE_TELEMETRY=1
mkdir -p "$YOLO_CONFIG_DIR" "$MPLCONFIGDIR" 2>/dev/null
say "YOLO_CONFIG_DIR : $YOLO_CONFIG_DIR"

# --- предполётная проверка --------------------------------------------------
# Именно этот импорт падал раньше. Проверяем ДО тяжёлого запуска и с диагнозом.
if ! "$PY" -c "import banner_parser" 2>>"$LOG"; then
    say "модуль banner_parser не импортируется из $(pwd)"
    say "содержимое каталога: $(ls -1 | tr '\n' ' ')"
    die "запускать нужно из каталога проекта; трассировка импорта — выше в логе"
fi
[ -f config.yaml ] || die "нет config.yaml в $(pwd)"

FREE_MB="$(df -Pm . | awk 'NR==2{print $4}')"
say "свободно на диске: ${FREE_MB} МБ"
[ "${FREE_MB:-0}" -gt 512 ] || say "ВНИМАНИЕ: меньше 512 МБ — веса моделей могут не докачаться"

# --- защита от параллельного запуска ---------------------------------------
# Два обхода на одной SQLite-базе будут драться за блокировки и дублировать работу.
exec 9>"$LOCK"
if command -v flock >/dev/null 2>&1; then
    flock -n 9 || die "обход уже запущен (блокировка $LOCK занята)"
else
    say "flock недоступен — параллельный запуск не проверяется"
fi

say "лог             : $LOG"
say "точка старта    : $LON,$LAT   лимит за запуск: $LIMIT"
say "остановить      : Ctrl-C или kill -TERM <pid>; состояние обхода в БД, "
say "                  повторный запуск продолжит с того же места"

# --- сам обход --------------------------------------------------------------
# -u обязателен: без него print() буферизуется и хвост лога пропадает при kill.
"$PY" -u -m banner_parser crawl \
    --lon "$LON" --lat "$LAT" --limit "$LIMIT" --log "$LOG" "$@"
RC=$?

# --- разбор причины остановки ----------------------------------------------
case "$RC" in
    0)   say "обход завершён штатно (код 0)" ;;
    1)   say "обход упал с исключением — трассировка в $LOG (искать «ИСКЛЮЧЕНИЕ»)" ;;
    2)   say "ошибка аргументов или конфигурации (код 2)" ;;
    130) say "остановлен с клавиатуры (Ctrl-C)" ;;
    143) say "остановлен сигналом TERM (kill/timeout/менеджер процессов)" ;;
    137) say "УБИТ SIGKILL (код 137): или OOM, или хостинг снёс сессию. "
         say "  Последняя строка «жив:» в логе показывает этап и память на тот момент" ;;
    *)   say "обход завершился с кодом $RC" ;;
esac
say "=== конец запуска (код $RC) ==="
exit "$RC"
